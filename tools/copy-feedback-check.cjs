// Browser verification of clipboard feedback; no project or server setting is modified.
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const { chromium, expect } = require('playwright/test');
const root = path.resolve(__dirname, '..');
const env = Object.fromEntries(fs.readFileSync(path.join(root,'dist/package-windows-amd64/config.env'),'utf8').split(/\r?\n/).filter(x => /^[A-Z0-9_]+=/.test(x.trim())).map(x => { const i=x.indexOf('=');return [x.slice(0,i).trim(),x.slice(i+1).trim().replace(/^(['"])(.*)\1$/,'$2')] }));
let browser;
(async () => {
  const base = process.env.UI_BASE_URL || 'http://127.0.0.1:5173';
  browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const context = await browser.newContext({viewport:{width:1672,height:940},reducedMotion:'reduce',permissions:['clipboard-read','clipboard-write']});
  assert((await context.request.post(base+'/api/v1/auth/login',{data:{username:env.GOSTREAM3D_ADMIN_USERNAME,password:env.GOSTREAM3D_ADMIN_PASSWORD}})).ok());
  const errors=[];
  const prepare = async page => {page.on('pageerror',e=>errors.push(e.message));await page.goto(base+'/admin#links');await expect(page.locator('.project-copy').first()).toBeVisible()};
  const page=await context.newPage();await prepare(page);
  const button=page.locator('.project-copy').first();const url=await button.getAttribute('title');
  const before=await page.locator('.project-management').boundingBox();
  await button.click();await expect(page.locator('.console-toast[role="status"]')).toContainText('复制成功');
  const written=await page.evaluate(()=>navigator.clipboard.readText());assert.equal(written,url);
  const after=await page.locator('.project-management').boundingBox();assert.equal(before.y,after.y,'Copy feedback must not move the project table');
  const box=await page.locator('.console-toast').boundingBox();assert(Math.abs(box.x+box.width/2-1672/2)<1);assert(box.y>=56&&box.y<100);
  await page.screenshot({path:path.join(root,'docs/ui-preview/copy-success-desktop.png')});
  await expect(page.locator('.console-toast')).toHaveCount(0,{timeout:4500});
  await button.click();await expect(page.locator('.console-toast')).toContainText('复制成功');
  await page.waitForTimeout(1100);await button.click();await page.waitForTimeout(2100);
  await expect(page.locator('.console-toast')).toContainText('复制成功');
  await expect(page.locator('.console-toast')).toHaveCount(0,{timeout:2500});
  console.log('Actual clipboard write, centered placement, stable layout, expiry and repeat reset: passed');
  const failure=await context.newPage();
  await failure.addInitScript(()=>{Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:()=>Promise.reject(new DOMException('Clipboard access denied','NotAllowedError'))}});document.execCommand=()=>false});
  await prepare(failure);await failure.locator('.project-copy').first().click();
  await expect(failure.locator('.console-toast[role="alert"]')).toContainText('复制失败');
  await failure.screenshot({path:path.join(root,'docs/ui-preview/copy-failure-desktop.png')});
  await expect(failure.locator('.console-toast')).toHaveCount(0,{timeout:5500});
  await failure.locator('.project-copy').first().click();await failure.getByRole('button',{name:'关闭复制提示'}).click();await expect(failure.locator('.console-toast')).toHaveCount(0);
  console.log('Both copy methods rejected, failure alert, expiry and manual close: passed');
  const race=await context.newPage();
  await race.addInitScript(()=>{
    window.__copyPending=[];
    Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:()=>new Promise((resolve,reject)=>window.__copyPending.push({resolve,reject}))}});
  });
  await prepare(race);await race.locator('.project-copy').first().click();await race.locator('.project-copy').first().click();
  await race.evaluate(()=>window.__copyPending[1].resolve());await expect(race.locator('.console-toast')).toContainText('复制成功');
  await race.evaluate(()=>window.__copyPending[0].reject(new Error('Earlier attempt failed')));await expect(race.locator('.console-toast')).toContainText('复制成功');
  await race.setViewportSize({width:390,height:844});
  const mobile=await race.locator('.console-toast').boundingBox();assert(mobile.x>=0&&mobile.x+mobile.width<=390);assert(Math.abs(mobile.x+mobile.width/2-195)<1);
  await race.screenshot({path:path.join(root,'docs/ui-preview/copy-success-mobile.png')});
  console.log('Out-of-order responses and mobile placement: passed');
  const unavailable=await context.newPage();await unavailable.addInitScript(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:undefined}));await prepare(unavailable);
  const fallbackURL=await unavailable.locator('.project-copy').first().getAttribute('title');
  await unavailable.locator('.project-copy').first().click();await expect(unavailable.locator('.console-toast')).toContainText('复制成功');
  const search=unavailable.getByRole('searchbox',{name:'搜索项目名称或地址'});await search.click();await search.press('Control+V');await expect(search).toHaveValue(fallbackURL);
  assert.deepEqual(errors,[]);
  console.log('Unavailable Clipboard API uses real selection copy; native paste and no uncaught browser errors: passed');
  await browser.close();
})().catch(async error=>{console.error(error);await browser?.close();process.exit(1)});
